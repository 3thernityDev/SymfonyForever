    public function get(string $code): ?SkillDefinition
    {
        return $this->skills[$code] ?? null;
    }

    /**
     * @return list<SkillDefinition>
     */
    public function forClass(CharacterClass $class): array
    {
        $list = array_values(array_filter(
            $this->skills,
            static fn (SkillDefinition $s): bool => $s->characterClass === $class,
        ));
        usort($list, static fn (SkillDefinition $a, SkillDefinition $b): int => $a->slot <=> $b->slot);

        return $list;
    }

    /**
     * @return list<SkillDefinition>
     */
    public function all(): array
    {
        return array_values($this->skills);
    }
